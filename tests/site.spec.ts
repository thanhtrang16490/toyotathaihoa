test('form error and confirmed response states',async ({page})=>{
  await page.goto('/nhan-bao-gia/')
  await page.getByLabel('Họ và tên').fill('Khách kiểm thử')
  await page.getByLabel('Số điện thoại').fill('0985123456')
  await page.getByRole('checkbox').check()
  await page.getByRole('button',{name:'Gửi yêu cầu'}).click()
  await expect(page.getByRole('status')).toContainText('chưa được kết nối')
  expect(await page.evaluate(()=>window.dataLayer?.some(event=>event.event==='lead_success'))).toBeFalsy()
  await page.route('**/api/lead/',route=>route.fulfill({json:{message:'Đại lý đã tiếp nhận yêu cầu của bạn.'}}))
  await page.getByRole('button',{name:'Gửi yêu cầu'}).click()
  await expect(page.getByRole('status')).toContainText('đã tiếp nhận')
  const events=await page.evaluate(()=>window.dataLayer)
  expect(events).toContainEqual({event:'lead_success',intent:'quote',page_path:'/nhan-bao-gia/'})
  expect(JSON.stringify(events)).not.toMatch(/0985123456|Khách kiểm thử/)
})
test('redirect, sitemap and staging robots',async ({request})=>{
  for(const [from,to] of [['/lien-he/','/contact/'],['/home-6/','/'],['/toyota/corolla-altis/','/xe-toyota-moi/'],['/dich-vu-dong-son/','/dich-vu-dong-son-toyota/']]){
    const redirect=await request.get(from,{maxRedirects:0})
    expect(redirect.status()).toBe(301)
    expect(new URL(redirect.headers().location,'http://127.0.0.1:4321').pathname).toBe(to)
    expect((await request.get(to,{maxRedirects:0})).status()).toBe(200)
  }
  const sitemap=await request.get('/sitemap.xml')
  expect(sitemap.ok()).toBe(true)
  expect(await sitemap.text()).toContain('/toyota/corolla-cross/')
  expect(await sitemap.text()).not.toContain('/nhan-bao-gia/')
  expect(await (await request.get('/robots.txt')).text()).toContain('Disallow: /')
})
test('service, contact and news can load without the source site',async ({page})=>{
  const outside:string[]=[]
  await page.route('**/*',route=>{
    const url=new URL(route.request().url())
    if(url.hostname==='127.0.0.1') return route.continue()
    outside.push(url.href)
    return route.abort()
  })
  await page.goto('/dich-vu/')
  await page.keyboard.press('Tab')
  await expect(page.getByRole('link',{name:'Đến nội dung'})).toBeFocused()
  await page.locator('.card-link[href="/dich-vu-bao-duong/"]').click()
  await page.getByRole('link',{name:'Đặt lịch bảo dưỡng'}).first().click()
  await expect(page.locator('input[name=intent]')).toHaveValue('service')
  await page.goto('/contact/')
  await expect(page.getByRole('link',{name:'Nhắn qua Zalo'})).toHaveAttribute('href','https://zalo.me/0985333388')
  await expect(page.locator('main').getByRole('link',{name:'Xem chỉ đường'})).toHaveAttribute('href',/^https:\/\/www\.google\.com\/maps\//)
  await page.goto('/tin-tuc/')
  await page.getByRole('link',{name:'Trang sau'}).click()
  await expect(page.getByRole('heading',{level:1})).toContainText('Trang 2')
  await page.locator('.card-link').first().click()
  const graph=JSON.parse(await page.locator('script[type="application/ld+json"]').innerText())['@graph']
  expect(graph.some((item:{'@type':string})=>item['@type']==='Article')).toBe(true)
  expect(outside).toEqual([])
})

test('legacy SEO issues stay out of the rebuilt pages', async ({request}) => {
  const legacy = await request.get('/corolla-cross-18v-car,749', {maxRedirects:0})
  expect(legacy.status()).toBe(301)
  expect(new URL(legacy.headers().location,'http://127.0.0.1:4321').pathname).toBe('/toyota/corolla-cross/')
  expect((await request.get('/unknown-car,999999')).status()).toBe(404)
  const sitemap = await (await request.get('/sitemap.xml')).text()
  expect(sitemap).not.toContain('/shop-2/')
  const used = await (await request.get('/xe-da-qua-su-dung/')).text()
  expect(used).toContain('Tồn kho đang được xác nhận')
  expect(used).not.toContain('class="card-link"')
  for (const model of ['hilux','corolla-cross','yaris-cross','innova-cross']) {
    const html = await (await request.get('/toyota/'+model+'/')).text()
    expect(html).toContain('Giá và thông số theo phiên bản đang được đối chiếu')
    expect(html).not.toContain('id="mau-xe"')
  }
})

