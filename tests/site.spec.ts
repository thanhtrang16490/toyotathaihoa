  await page.getByRole('button',{name:'Corolla Cross SUV',exact:true}).click()
  await expect(page.getByRole('dialog',{name:'Menu Toyota'}).getByRole('heading',{name:'Corolla Cross',exact:true})).toBeFocused()
  await expect(page.getByRole('link',{name:'Tổng quan mẫu xe'})).toHaveAttribute('href','/toyota/corolla-cross/')
  const back = page.getByRole('button',{name:test.info().project.name==='mobile'?'Quay lại menu':'Xe Toyota',exact:true})
  await back.click()
  await page.getByRole('link',{name:'Xem tất cả dòng xe'}).click()
  await page.getByLabel('Tìm theo tên xe').fill('khong co xe nay')
  await expect(page.locator('#model-count')).toHaveText('Không tìm thấy mẫu xe phù hợp.')
